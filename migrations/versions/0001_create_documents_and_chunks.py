    op.create_table(
        "chunks",
        sa.Column("id", sa.Integer(), autoincrement=True, nullable=False),
        sa.Column("document_id", sa.Integer(), nullable=False),
        sa.Column("chunk_index", sa.Integer(), nullable=False),
        sa.Column("content", sa.Text(), nullable=False),
        sa.Column("embedding", pgvector.sqlalchemy.Vector(dim=768), nullable=False),
        sa.Column("embedding_model", sa.Text(), nullable=False),
        sa.Column("metadata", postgresql.JSONB(astext_type=sa.Text()), nullable=False),
        # GENERATED ALWAYS ... STORED: PostgreSQL maintains this from `content`,
        # so application code never writes it and it cannot drift out of sync.
        sa.Column(
            "search_vector",
            postgresql.TSVECTOR(),
            sa.Computed("to_tsvector('english', content)", persisted=True),
            nullable=True,
        ),
        sa.ForeignKeyConstraint(["document_id"], ["documents.id"], ondelete="CASCADE"),
        sa.PrimaryKeyConstraint("id"),
    )

    # GIN is the index type for full-text search; without it keyword search
    # degrades to a sequential scan over every chunk.
    op.create_index("ix_chunks_search_vector", "chunks", ["search_vector"], postgresql_using="gin")
    op.create_index("ix_chunks_document_id", "chunks", ["document_id"])

    # No vector index (HNSW/IVFFlat) on purpose: at ~9,000 chunks an exact scan is
    # fast and exact. Add one when the corpus grows — see docs/adr/001.


